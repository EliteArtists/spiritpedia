  ADD CONSTRAINT user_profiles_signup_platform_known
  CHECK (signup_platform IS NULL OR signup_platform IN ('web', 'app'));

COMMENT ON COLUMN public.user_profiles.signup_platform IS
  'web or app: where the account was created, for Sign-ups over time. NULL for accounts made before 0021.';


-- 3. Layer 1 tables ----------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.activity_events (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id      UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  kind         TEXT NOT NULL,
  content_type TEXT,
  content_slug TEXT,
  subjects     TEXT[] NOT NULL DEFAULT '{}',
  platform     TEXT NOT NULL,
  occurred_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE public.activity_events IS
  'Layer 1: one member''s own activity, recorded only while learning is on. No search text. Kept 30 days (purge_activity). The member may read and delete their own; written only by log_activity(). No admin page reads it.';

CREATE INDEX IF NOT EXISTS activity_events_user_idx ON public.activity_events (user_id, occurred_at);
CREATE INDEX IF NOT EXISTS activity_events_age_idx ON public.activity_events (occurred_at);

ALTER TABLE public.activity_events ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Members read their own activity" ON public.activity_events;
CREATE POLICY "Members read their own activity" ON public.activity_events
  FOR SELECT TO authenticated USING (auth.uid() = user_id);

DROP POLICY IF EXISTS "Members delete their own activity" ON public.activity_events;
CREATE POLICY "Members delete their own activity" ON public.activity_events
  FOR DELETE TO authenticated USING (auth.uid() = user_id);


CREATE TABLE IF NOT EXISTS public.subject_affinity (
  user_id      UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  subject_slug TEXT NOT NULL,
  score        REAL NOT NULL DEFAULT 0 CHECK (score >= 0),
  updated_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, subject_slug)
);

COMMENT ON TABLE public.subject_affinity IS
  'Layer 1: how much a member has explored each subject. Halves every 30 days; read the current value as score * 0.5 ^ (days since updated_at / 30). Owner-only; deleted when learning is switched off or the account is deleted.';

ALTER TABLE public.subject_affinity ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Members read their own affinity" ON public.subject_affinity;
CREATE POLICY "Members read their own affinity" ON public.subject_affinity
  FOR SELECT TO authenticated USING (auth.uid() = user_id);

DROP POLICY IF EXISTS "Members delete their own affinity" ON public.subject_affinity;
CREATE POLICY "Members delete their own affinity" ON public.subject_affinity
  FOR DELETE TO authenticated USING (auth.uid() = user_id);


-- 4. Layer 2 tables (anonymous; no policies: service role only) --------------

CREATE TABLE IF NOT EXISTS public.activity_daily (
  day          DATE NOT NULL,
  platform     TEXT NOT NULL,
  kind         TEXT NOT NULL,
  content_type TEXT NOT NULL,
  content_slug TEXT NOT NULL,
  count        INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY (day, platform, kind, content_type, content_slug)
);

COMMENT ON TABLE public.activity_daily IS
  'Layer 2: how often each item was opened, watched, saved, unsaved, shared or reviewed, per day and platform. No user, device, session or IP. Kept 25 months. Service role only.';

ALTER TABLE public.activity_daily ENABLE ROW LEVEL SECURITY;


CREATE TABLE IF NOT EXISTS public.subject_daily (
  day          DATE NOT NULL,
  platform     TEXT NOT NULL,
  kind         TEXT NOT NULL,
  subject_slug TEXT NOT NULL,
  count        INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY (day, platform, kind, subject_slug)
);

COMMENT ON TABLE public.subject_daily IS
  'Layer 2: activity per subject per day and platform, for Rising subjects. Anonymous. Kept 25 months. Service role only.';

ALTER TABLE public.subject_daily ENABLE ROW LEVEL SECURITY;


CREATE TABLE IF NOT EXISTS public.search_misses (
  day      DATE NOT NULL,
  platform TEXT NOT NULL,
  term     TEXT NOT NULL CHECK (char_length(term) BETWEEN 1 AND 60),
  count    INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY (day, platform, term)
);

COMMENT ON TABLE public.search_misses IS
  'Layer 2: searches that found nothing, cleaned (lower case, single spaces, at most 60 characters; anything with an @ or three digits in a row is never kept). Never a crisis search. Anonymous. Kept 90 days. Service role only.';

ALTER TABLE public.search_misses ENABLE ROW LEVEL SECURITY;


-- 5. Switching learning off deletes what was learned ------------------------

CREATE OR REPLACE FUNCTION public.user_preferences_learning_changed()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    DELETE FROM public.activity_events WHERE user_id = OLD.user_id;
    DELETE FROM public.subject_affinity WHERE user_id = OLD.user_id;
    RETURN OLD;
  END IF;

  IF TG_OP = 'INSERT' THEN
    NEW.learning_changed_at := CASE WHEN NEW.learning_enabled THEN now() ELSE NULL END;
    RETURN NEW;
  END IF;

  IF NEW.learning_enabled IS DISTINCT FROM OLD.learning_enabled THEN
    NEW.learning_changed_at := now();
    IF NOT NEW.learning_enabled THEN
      DELETE FROM public.activity_events WHERE user_id = NEW.user_id;
      DELETE FROM public.subject_affinity WHERE user_id = NEW.user_id;
    END IF;
  ELSE
    NEW.learning_changed_at := OLD.learning_changed_at;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS user_preferences_learning_changed ON public.user_preferences;
CREATE TRIGGER user_preferences_learning_changed
  BEFORE INSERT OR UPDATE ON public.user_preferences
  FOR EACH ROW EXECUTE FUNCTION public.user_preferences_learning_changed();

DROP TRIGGER IF EXISTS user_preferences_learning_removed ON public.user_preferences;
CREATE TRIGGER user_preferences_learning_removed
  AFTER DELETE ON public.user_preferences
  FOR EACH ROW EXECUTE FUNCTION public.user_preferences_learning_changed();

REVOKE ALL ON FUNCTION public.user_preferences_learning_changed() FROM PUBLIC, anon, authenticated;


-- 6. log_activity(): the only writer ----------------------------------------
--
-- p_events: up to 50 objects of the shape
--   { "kind": "open", "content_type": "video", "content_slug": "…",
--     "subjects": ["reiki", …], "term": "…", "no_results": true }
-- term and no_results are read only for kind 'search'. p_user is the caller,
-- as the route established it from their token, or NULL when signed out.
-- Returns how many events were counted.

CREATE OR REPLACE FUNCTION public.log_activity(p_platform TEXT, p_events JSONB, p_user UUID DEFAULT NULL)
RETURNS INTEGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  c_kinds CONSTANT TEXT[] := ARRAY['open', 'watch', 'save', 'unsave', 'share', 'review', 'pill', 'filter', 'search'];
  c_content_kinds CONSTANT TEXT[] := ARRAY['open', 'watch', 'save', 'unsave', 'share', 'review'];
  c_types CONSTANT TEXT[] := ARRAY['healer', 'publisher', 'book', 'video', 'course', 'free_resource'];
  c_half_life_days CONSTANT REAL := 30;
  v_learning BOOLEAN := false;
  v_hidden TEXT[] := '{}';
  v_event JSONB;
  v_kind TEXT;
  v_type TEXT;
  v_slug TEXT;
  v_subjects TEXT[];
  v_term TEXT;
  v_weight REAL;
  v_subject TEXT;
  v_counted INTEGER := 0;
  v_today DATE := (now() AT TIME ZONE 'UTC')::date;
BEGIN
  IF p_platform IS NULL OR p_platform NOT IN ('web', 'app') THEN
    RAISE EXCEPTION 'Unknown platform.';
  END IF;
  IF p_events IS NULL OR jsonb_typeof(p_events) <> 'array' THEN
    RETURN 0;
  END IF;

  IF p_user IS NOT NULL THEN
    SELECT learning_enabled INTO v_learning FROM public.user_preferences WHERE user_id = p_user;
    v_learning := coalesce(v_learning, false);
    IF v_learning THEN
      SELECT coalesce(hidden_subjects, '{}') INTO v_hidden FROM public.user_interests WHERE user_id = p_user;
      v_hidden := coalesce(v_hidden, '{}');
    END IF;
  END IF;

  FOR v_event IN SELECT value FROM jsonb_array_elements(p_events) WITH ORDINALITY AS e(value, n) WHERE n <= 50
  LOOP
    v_kind := v_event ->> 'kind';
    CONTINUE WHEN v_kind IS NULL OR NOT (v_kind = ANY (c_kinds));

    v_type := v_event ->> 'content_type';
    v_slug := left(v_event ->> 'content_slug', 200);
    IF v_type IS NOT NULL AND NOT (v_type = ANY (c_types)) THEN
      v_type := NULL;
      v_slug := NULL;
    END IF;

    -- Only real subjects, at most 20.
    SELECT coalesce(array_agg(DISTINCT s.slug), '{}') INTO v_subjects
      FROM public.subjects s
     WHERE s.slug IN (
       SELECT x FROM jsonb_array_elements_text(
         CASE WHEN jsonb_typeof(v_event -> 'subjects') = 'array' THEN v_event -> 'subjects' ELSE '[]'::jsonb END
       ) WITH ORDINALITY AS t(x, n) WHERE n <= 20
     );

    -- Layer 2: anonymous totals.
    IF v_kind = ANY (c_content_kinds) AND v_type IS NOT NULL AND v_slug IS NOT NULL AND v_slug <> '' THEN
      INSERT INTO public.activity_daily AS a (day, platform, kind, content_type, content_slug, count)
      VALUES (v_today, p_platform, v_kind, v_type, v_slug, 1)
      ON CONFLICT (day, platform, kind, content_type, content_slug) DO UPDATE SET count = a.count + 1;
    END IF;

    FOREACH v_subject IN ARRAY v_subjects LOOP
      INSERT INTO public.subject_daily AS d (day, platform, kind, subject_slug, count)
      VALUES (v_today, p_platform, v_kind, v_subject, 1)
      ON CONFLICT (day, platform, kind, subject_slug) DO UPDATE SET count = d.count + 1;
    END LOOP;

    IF v_kind = 'search' AND (v_event -> 'no_results') = 'true'::jsonb THEN
      v_term := regexp_replace(lower(trim(coalesce(v_event ->> 'term', ''))), '\s+', ' ', 'g');
      IF char_length(v_term) BETWEEN 1 AND 60 AND v_term !~ '@' AND v_term !~ '[0-9]{3,}' THEN
        INSERT INTO public.search_misses AS m (day, platform, term, count)
        VALUES (v_today, p_platform, v_term, 1)
        ON CONFLICT (day, platform, term) DO UPDATE SET count = m.count + 1;
      END IF;
    END IF;

    -- Layer 1: only with the switch on. No search text.
    IF v_learning THEN
      INSERT INTO public.activity_events (user_id, kind, content_type, content_slug, subjects, platform)
      VALUES (p_user, v_kind, v_type, v_slug, v_subjects, p_platform);

      v_weight := CASE v_kind
        WHEN 'open' THEN 1 WHEN 'watch' THEN 2 WHEN 'save' THEN 4 WHEN 'unsave' THEN -4
        WHEN 'share' THEN 3 WHEN 'review' THEN 3 ELSE 1 END;

      FOREACH v_subject IN ARRAY v_subjects LOOP
        CONTINUE WHEN v_subject = ANY (v_hidden);
        INSERT INTO public.subject_affinity AS f (user_id, subject_slug, score, updated_at)
        VALUES (p_user, v_subject, greatest(0, v_weight), now())
        ON CONFLICT (user_id, subject_slug) DO UPDATE SET
          score = greatest(0,
            f.score * power(0.5, extract(epoch FROM now() - f.updated_at) / (c_half_life_days * 86400))
            + v_weight),
          updated_at = now();
      END LOOP;
    END IF;

    v_counted := v_counted + 1;
  END LOOP;

  RETURN v_counted;
END;
$$;

COMMENT ON FUNCTION public.log_activity(TEXT, JSONB, UUID) IS
  'The only writer of activity: anonymous totals always; the member''s own events and scores only when p_user has learning on. Service role only (the website''s /api/activity).';

REVOKE ALL ON FUNCTION public.log_activity(TEXT, JSONB, UUID) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.log_activity(TEXT, JSONB, UUID) TO service_role;


-- 7. Retention ---------------------------------------------------------------
-- Run daily by the website's cron. Returns what it removed.

CREATE OR REPLACE FUNCTION public.purge_activity()
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_events INTEGER; v_misses INTEGER; v_daily INTEGER; v_subjects INTEGER;
BEGIN
  DELETE FROM public.activity_events WHERE occurred_at < now() - interval '30 days';
  GET DIAGNOSTICS v_events = ROW_COUNT;
  DELETE FROM public.search_misses WHERE day < current_date - 90;
  GET DIAGNOSTICS v_misses = ROW_COUNT;
  DELETE FROM public.activity_daily WHERE day < (current_date - interval '25 months')::date;
  GET DIAGNOSTICS v_daily = ROW_COUNT;
  DELETE FROM public.subject_daily WHERE day < (current_date - interval '25 months')::date;
  GET DIAGNOSTICS v_subjects = ROW_COUNT;
  RETURN jsonb_build_object('activity_events', v_events, 'search_misses', v_misses,
                            'activity_daily', v_daily, 'subject_daily', v_subjects);
END;
$$;

REVOKE ALL ON FUNCTION public.purge_activity() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.purge_activity() TO service_role;


-- 8. The Activity dashboard's reads (totals only; service role only) --------
-- p_platform: 'web', 'app', or NULL for both.

-- Most opened (p_kind 'open') or most saved (p_kind 'saved': saves minus
-- unsaves), between two days inclusive.
CREATE OR REPLACE FUNCTION public.activity_top(p_kind TEXT, p_from DATE, p_to DATE, p_platform TEXT DEFAULT NULL, p_limit INTEGER DEFAULT 20)
RETURNS TABLE (content_type TEXT, content_slug TEXT, total BIGINT)
LANGUAGE sql STABLE
SET search_path = public, pg_temp
AS $$
  SELECT a.content_type, a.content_slug,
         sum(CASE WHEN p_kind = 'saved' AND a.kind = 'unsave' THEN -a.count ELSE a.count END) AS total
    FROM public.activity_daily a
   WHERE a.day BETWEEN p_from AND p_to
     AND (p_platform IS NULL OR a.platform = p_platform)
     AND (CASE WHEN p_kind = 'saved' THEN a.kind IN ('save', 'unsave') ELSE a.kind = p_kind END)
   GROUP BY a.content_type, a.content_slug
  HAVING sum(CASE WHEN p_kind = 'saved' AND a.kind = 'unsave' THEN -a.count ELSE a.count END) > 0
   ORDER BY total DESC, a.content_slug
   LIMIT least(coalesce(p_limit, 20), 100);
$$;

-- Rising subjects: the last 7 days against the weekly average of the 4 weeks
-- before. All activity kinds count.
CREATE OR REPLACE FUNCTION public.subject_rising(p_platform TEXT DEFAULT NULL, p_limit INTEGER DEFAULT 10)
RETURNS TABLE (subject_slug TEXT, this_week BIGINT, weekly_before NUMERIC)
LANGUAGE sql STABLE
SET search_path = public, pg_temp
AS $$
  SELECT d.subject_slug,
         sum(d.count) FILTER (WHERE d.day > current_date - 7) AS this_week,
         round(coalesce(sum(d.count) FILTER (WHERE d.day <= current_date - 7), 0) / 4.0, 1) AS weekly_before
    FROM public.subject_daily d
   WHERE d.day > current_date - 35
     AND (p_platform IS NULL OR d.platform = p_platform)
   GROUP BY d.subject_slug
  HAVING coalesce(sum(d.count) FILTER (WHERE d.day > current_date - 7), 0) > 0
   ORDER BY (sum(d.count) FILTER (WHERE d.day > current_date - 7))
            - coalesce(sum(d.count) FILTER (WHERE d.day <= current_date - 7), 0) / 4.0 DESC
   LIMIT least(coalesce(p_limit, 10), 50);
$$;

-- Searches with no results, made at least p_min times in the period.
CREATE OR REPLACE FUNCTION public.search_misses_top(p_from DATE, p_to DATE, p_platform TEXT DEFAULT NULL, p_min INTEGER DEFAULT 2, p_limit INTEGER DEFAULT 50)
RETURNS TABLE (term TEXT, total BIGINT)
LANGUAGE sql STABLE
SET search_path = public, pg_temp
AS $$
  SELECT m.term, sum(m.count) AS total
    FROM public.search_misses m
   WHERE m.day BETWEEN p_from AND p_to
     AND (p_platform IS NULL OR m.platform = p_platform)
   GROUP BY m.term
  HAVING sum(m.count) >= greatest(coalesce(p_min, 2), 2)
   ORDER BY total DESC, m.term
   LIMIT least(coalesce(p_limit, 50), 200);
$$;

-- Sign-ups per day, by where they came from ('unknown' before 0021).
CREATE OR REPLACE FUNCTION public.signups_by_day(p_from DATE, p_to DATE)
RETURNS TABLE (day DATE, platform TEXT, total BIGINT)
LANGUAGE sql STABLE
SET search_path = public, pg_temp
AS $$
  SELECT (p.created_at AT TIME ZONE 'UTC')::date AS day,
         coalesce(p.signup_platform, 'unknown') AS platform,
         count(*) AS total
    FROM public.user_profiles p
   WHERE (p.created_at AT TIME ZONE 'UTC')::date BETWEEN p_from AND p_to
   GROUP BY 1, 2
   ORDER BY 1, 2;
$$;

