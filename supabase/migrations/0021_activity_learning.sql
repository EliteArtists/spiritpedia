-- 0021: activity learning (layer 1) and anonymous activity totals (layer 2).
--
-- Dev first, then live. Safe to run twice.
--
-- LAYER 1 — personal learning. Signed-in members only, and only with
-- "Let Spiritpedia learn from what I explore" switched on
-- (user_preferences.learning_enabled, off by default). What they open, watch,
-- save, unsave, share and review, the pills and filters they tap, and the
-- subjects their searches lead to become per-subject scores that halve every
-- 30 days (subject_affinity). The ranking reads them just below More of. They
-- never hide anything, and Never show subjects are never scored. No search
-- text is stored here. Raw events are kept 30 days. Switching learning off
-- deletes the events and the scores at once. Only the member can read their
-- own; no admin page reads them.
--
-- LAYER 2 — anonymous totals, for everyone, signed in or out. Counts per day
-- (activity_daily, subject_daily) and searches that found nothing
-- (search_misses), with no user, device, session or IP. Admin reads them
-- through the server, as totals only.
--
-- Everything is written by ONE function, log_activity(), which only the
-- service role may call: the website's /api/activity route checks the batch
-- (including a second crisis check), identifies the caller from their own
-- token, and passes the user id when there is one. No browser or phone can
-- write these tables directly.
--
-- Crisis: a search caught by the crisis intercept never produces an event, in
-- the app or on the website, and the route drops any that do. Nothing here
-- changes the intercept.


-- 1. The switch ------------------------------------------------------------

ALTER TABLE public.user_preferences
  ADD COLUMN IF NOT EXISTS learning_enabled BOOLEAN NOT NULL DEFAULT false,
  ADD COLUMN IF NOT EXISTS learning_changed_at TIMESTAMPTZ;

COMMENT ON COLUMN public.user_preferences.learning_enabled IS
  '"Let Spiritpedia learn from what I explore." Off by default. Turning it off deletes activity_events and subject_affinity for the member (trigger).';
COMMENT ON COLUMN public.user_preferences.learning_changed_at IS
  'When the switch last changed: the record of consent. Set by trigger.';


-- 2. Where a sign-up came from --------------------------------------------

ALTER TABLE public.user_profiles
  ADD COLUMN IF NOT EXISTS signup_platform TEXT;

ALTER TABLE public.user_profiles
  DROP CONSTRAINT IF EXISTS user_profiles_signup_platform_known;
